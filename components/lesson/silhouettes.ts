/** Výřez siluety: obal obou póz (i s hlavou a tloušťkou čáry) + zem, aby postava vyplnila kartu. */
const MIN_FRAME = { w: 140, h: 72 } as const;
export function poseFrame(id: SilhouetteId, pad = 8): { x: number; y: number; w: number; h: number } {
  const pts = SILHOUETTES[id].flatMap((p) => [
    [p.head[0] - HEAD_R, p.head[1] - HEAD_R] as P, [p.head[0] + HEAD_R, p.head[1] + HEAD_R] as P, ...Object.values(p.joints),
  ]);
  const xs = pts.map((q) => q[0]);
  const ys = pts.map((q) => q[1]);
  // Minimální výřez drží tloušťku čar v rozumných mezích i u ležících póz (plank by jinak zbytněl).
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2;
  const w = Math.max(Math.max(...xs) - Math.min(...xs) + 2 * pad, MIN_FRAME.w);
  const bottom = GROUND_Y + 4;
  const h = Math.max(bottom - (Math.min(...ys) - pad), MIN_FRAME.h);
  return { x: cx - w / 2, y: bottom - h, w, h };
}
